//! The theme as Typst set and show rules, and the helper functions the body calls.

use std::fmt::Write as _;

use crate::theme::{Color, Length, LengthUnit, Theme};

use super::escape::string;

/// The bundled serif family: the fallback of body and heading fonts.
pub(super) const SERIF: &str = "Libertinus Serif";
/// The bundled monospace family: the fallback of the code font.
pub(super) const MONO: &str = "DejaVu Sans Mono";
/// The marker line between the preamble and the body.
pub(super) const BODY_MARKER: &str = "// --- body\n";

/// CSS and platform family names that mean "the default font of this kind"; they map
/// to the bundled fallback without a warning.
const GENERIC: &[&str] = &[
    "serif",
    "sans-serif",
    "monospace",
    "system-ui",
    "ui-serif",
    "ui-sans-serif",
    "ui-monospace",
    "ui-rounded",
    "cursive",
    "fantasy",
    "math",
    "-apple-system",
    "blinkmacsystemfont",
];

/// A theme font list resolved against the available families.
pub(super) struct FontList {
    /// The available families of the list, in order, then the fallback.
    pub families: Vec<String>,
    /// The list named only families that are neither available nor generic.
    pub missing: Option<String>,
}

/// The families of the comma-separated `list` that are in `available` (ignoring case,
/// with their available spelling), then `fallback`.
pub(super) fn font_list(list: &str, available: &[String], fallback: &str) -> FontList {
    let mut families: Vec<String> = Vec::new();
    let mut generic = false;
    for name in list.split(',') {
        let name = name.trim().trim_matches(|c| c == '"' || c == '\'').trim();
        if name.is_empty() {
            continue;
        }
        if GENERIC.contains(&name.to_ascii_lowercase().as_str()) {
            generic = true;
            continue;
        }
        if let Some(family) = available.iter().find(|f| f.eq_ignore_ascii_case(name))
            && !families.contains(family)
        {
            families.push(family.clone());
        }
    }
    let missing = (families.is_empty() && !generic && !list.trim().is_empty())
        .then(|| list.trim().to_owned());
    if !families.iter().any(|f| f == fallback) {
        families.push(fallback.to_owned());
    }
    FontList { families, missing }
}

/// A Typst color.
pub(super) fn color(c: Color) -> String {
    format!("rgb(\"{c}\")")
}

/// A Typst array of font families.
fn families(list: &[String]) -> String {
    let items: Vec<String> = list.iter().map(|f| string(f)).collect();
    format!("({},)", items.join(", "))
}

/// `length` in Typst: `em` stays, `rem` is relative to `body` (in points), `px` is ¾pt.
fn length(length: Length, body: f32) -> String {
    let value = match length.unit {
        LengthUnit::Em => return format!("{}em", number(length.value)),
        LengthUnit::Rem => length.value * body,
        LengthUnit::Pt => length.value,
        LengthUnit::Px => length.value * 0.75,
    };
    format!("{}pt", number(value))
}

/// The body font size in points; `em`/`rem` are relative to Typst's default of 11pt.
fn body_size(length: Length) -> f32 {
    match length.unit {
        LengthUnit::Em | LengthUnit::Rem => length.value * 11.0,
        LengthUnit::Pt => length.value,
        LengthUnit::Px => length.value * 0.75,
    }
}

/// A number without needless decimals (`1.5`, `11`).
fn number(value: f32) -> String {
    let rounded = (value * 1000.0).round() / 1000.0;
    format!("{rounded}")
}

/// What the preamble needs besides the theme.
pub(super) struct Page<'a> {
    pub paper: &'a str,
    pub title: Option<&'a str>,
    pub lang: Option<&'a str>,
    pub body_fonts: &'a [String],
    pub heading_fonts: &'a [String],
    pub mono_fonts: &'a [String],
    /// The virtual path of the `overrides.pdf` template.
    pub template: Option<&'a str>,
}

/// The preamble for `theme`: document metadata, page, text and paragraph settings,
/// one show rule per element, the helpers and the template; ends with
/// [`BODY_MARKER`].
#[allow(clippy::too_many_lines)] // one rule per element
pub(super) fn preamble(theme: &Theme, page: &Page<'_>) -> String {
    let c = &theme.colors;
    let size = body_size(theme.fonts.size);
    let mut out = String::from(
        "// Generated by mrq: the theme as set and show rules, helpers, then the body.\n",
    );
    let mut line = |text: String| {
        out.push_str(&text);
        out.push('\n');
    };
    if let Some(title) = page.title {
        line(format!("#set document(title: {})", string(title)));
    }
    line(format!(
        "#set page(paper: {}, margin: 2.5cm, fill: {})",
        string(page.paper),
        color(c.background)
    ));
    let lang = page
        .lang
        .map(|lang| format!(", lang: {}", string(lang)))
        .unwrap_or_default();
    line(format!(
        "#set text(font: {}, size: {}pt, fill: {}{lang})",
        families(page.body_fonts),
        number(size),
        color(c.foreground)
    ));
    // Typst's leading is the gap between lines, about the line height less 0.7em.
    let leading = (theme.fonts.line_height - 0.7).max(0.2);
    line(format!(
        "#set par(leading: {}em, spacing: {}em)",
        number(leading),
        number(leading + 0.5)
    ));
    line(format!(
        "#show heading: set text(font: {}, fill: {})",
        families(page.heading_fonts),
        color(c.heading)
    ));
    line("#show heading: set block(above: 1.4em, below: 0.8em)".to_owned());
    for level in 1..=6u8 {
        let style = theme.headings.level(level);
        let mut args = Vec::new();
        if let Some(heading_size) = style.size {
            args.push(format!("size: {}", length(heading_size, size)));
        }
        if let Some(weight) = style.weight {
            args.push(format!("weight: {}", weight.number()));
        }
        if let Some(italic) = style.italic {
            args.push(format!(
                "style: {}",
                if italic { "\"italic\"" } else { "\"normal\"" }
            ));
        }
        if let Some(fill) = style.color {
            args.push(format!("fill: {}", color(fill)));
        }
        if !args.is_empty() {
            line(format!(
                "#show heading.where(level: {level}): set text({})",
                args.join(", ")
            ));
        }
        if style.underline == Some(true) {
            line(format!(
                "#show heading.where(level: {level}): it => block(width: 100%, stroke: (bottom: 0.5pt + {}), inset: (bottom: 0.3em), it)",
                color(c.border)
            ));
        }
    }
    line(format!("#show link: set text(fill: {})", color(c.accent)));
    line(format!(
        "#show raw: set text(font: {})",
        families(page.mono_fonts)
    ));
    line(format!(
        "#show raw.where(block: false): it => box(fill: {}, inset: (x: 2pt), outset: (y: 2pt), radius: 2pt, text(fill: {}, it))",
        color(c.code_background),
        color(c.code_foreground)
    ));
    line(format!(
        "#set table(stroke: 0.5pt + {}, inset: 6pt)",
        color(c.border)
    ));
    line(format!(
        "#set footnote.entry(separator: line(length: 30%, stroke: 0.5pt + {}))",
        color(c.border)
    ));
    line(format!(
        "#show footnote.entry: set text(fill: {})",
        color(c.muted)
    ));
    line(format!(
        "#let mrq-code(fill: none, color: none, lines) = block(width: 100%, fill: fill, inset: 8pt, radius: 3pt, {{\n  \
         set text(font: {}, size: 0.85em, fill: color)\n  \
         set par(justify: false, leading: 0.5em)\n  \
         lines.map(line => line.map(((text, fill, bold, italic, underline)) => {{\n    \
         let span = std.text(fill: if fill == none {{ color }} else {{ fill }}, weight: if bold {{ \"bold\" }} else {{ \"regular\" }}, style: if italic {{ \"italic\" }} else {{ \"normal\" }}, text)\n    \
         if underline {{ std.underline(span) }} else {{ span }}\n  \
         }}).join()).join(linebreak())\n}})",
        families(page.mono_fonts)
    ));
    line(format!(
        "#let mrq-quote(body) = block(stroke: (left: 2pt + {}), inset: (left: 10pt, y: 2pt), text(fill: {}, body))",
        color(c.border),
        color(c.muted)
    ));
    line(
        "#let mrq-alert(color, title, body) = block(width: 100%, stroke: (left: 3pt + color), inset: (left: 10pt, y: 4pt), {\n  \
         if title != none { block(below: 0.6em, text(fill: color, weight: \"bold\", title)) }\n  \
         body\n})"
            .to_owned(),
    );
    line(format!(
        "#let mrq-rule() = line(length: 100%, stroke: 0.5pt + {})",
        color(c.border)
    ));
    line(format!(
        "#let mrq-task(done) = box(text(font: {}, if done [☑] else [☐]))",
        families(page.mono_fonts)
    ));
    line(format!(
        "#let mrq-tag(body) = text(fill: {}, body)",
        color(c.accent)
    ));
    line(
        "#let mrq-image(path, alt: none) = box(layout(size => {\n  \
         let img = image(path, alt: alt)\n  \
         if measure(img).width > size.width { image(path, alt: alt, width: size.width) } else { img }\n}))"
            .to_owned(),
    );
    line("#let mrq-diagram(path) = align(center, mrq-image(path))".to_owned());
    if let Some(template) = page.template {
        line(format!("#import {}: template", string(template)));
        line("#show: template".to_owned());
    }
    let _ = write!(out, "{BODY_MARKER}");
    out
}
