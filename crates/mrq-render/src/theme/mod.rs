//! Render themes: the portable description of colors, fonts, heading styles and the
//! code-highlighting theme that every backend maps as well as it can.
//!
//! # Built-in themes
//!
//! [`BUILTIN_THEMES`]: `light` ([`Theme::default`]), `dark`, `github` and `paper`.
//! All but `light` are YAML files in `src/theme/builtin/` that extend `light`.
//!
//! # Loading and inheritance
//!
//! A theme file is YAML of the shape of [`Theme`] (README, `#### Styles`). It is
//! checked against [`Theme`] on its own first, so an unknown key or a bad value is an
//! error with the file and line ([`ThemeError::Invalid`]). Then it is merged over the
//! theme it `extends` (a built-in name or a path relative to the file; `light` without
//! `extends`): mappings key by key, recursively, so `headings.h1.italic` keeps the base
//! `h1` size; any other value, `null` included, replaces the inherited one. Chains of
//! files are followed, and a file reached twice is a [`ThemeError::Cycle`].
//!
//! Relative paths (`overrides.*`, and `code.theme` when it names a `.tmTheme` file)
//! resolve against the directory of the file that sets them, so they keep working when
//! a theme in another directory extends that file. A loaded theme's `extends` is `None`.
//!
//! # Schema
//!
//! Every type derives [`schemars::JsonSchema`]; [`schema_json`] is the published JSON
//! Schema, checked in at `crates/mrq-render/schema/mrq-theme.schema.json` and
//! regenerated by `just schema`.

mod load;
mod model;
mod value;

pub use load::{BUILTIN_THEMES, ThemeError, builtin_sources};
pub use model::{AlertColors, CodeStyle, Colors, Fonts, HeadingStyle, Headings, Overrides, Theme};
pub use value::{Color, ColorError, FontWeight, Length, LengthError, LengthUnit};

/// The JSON Schema of a theme file.
pub fn schema() -> schemars::Schema {
    schemars::schema_for!(Theme)
}

/// [`schema`] as pretty-printed JSON with a trailing newline; the content of
/// `crates/mrq-render/schema/mrq-theme.schema.json`.
pub fn schema_json() -> String {
    let mut json = serde_json::to_string_pretty(&schema()).unwrap_or_default();
    json.push('\n');
    json
}
